#!/usr/bin/env node
/**
 * Builds standalone/indesign-bridge.mjs: the whole bridge (server + dashboard) in a
 * single dependency-free file, so it can be dropped on any machine with Node 18+ and
 * started with:  node indesign-bridge.mjs
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const server = fs.readFileSync(path.join(root, "bridge", "server.mjs"), "utf8").replace(/^#![^\n]*\n/, "");
const dashboard = fs.readFileSync(path.join(root, "bridge", "public", "index.html"), "utf8");
const outFile = path.join(root, "standalone", "indesign-bridge.mjs");

const marker = 'const DASHBOARD_B64 = "";';
if (!server.includes(marker)) {
  console.error("Could not find the DASHBOARD_B64 placeholder in bridge/server.mjs");
  process.exit(1);
}

const banner = `/**
 * InDesign <-> Arena bridge - standalone single file build.
 *
 *   node indesign-bridge.mjs
 *
 * Env: PORT (8787), BRIDGE_TOKEN, PUBLIC_URL, BRIDGE_DATA_DIR
 *      UPSTREAM + UPSTREAM_TOKEN - relay jobs to another bridge (e.g. the Arena sandbox)
 *
 * Generated by scripts/bundle-standalone.mjs - edit bridge/server.mjs instead.
 */
`;

const bundled = server.replace(marker, `const DASHBOARD_B64 = "${Buffer.from(dashboard, "utf8").toString("base64")}";`);
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, banner + bundled);

console.log(`  built standalone/indesign-bridge.mjs (${(fs.statSync(outFile).size / 1024).toFixed(1)} KB)`);
